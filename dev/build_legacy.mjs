// Build the legacy bundle for old TVs (webOS 4.x = Chrome 53: no ES modules, no object spread / ?. / ??, no WebGL2):
//   node dev/build_legacy.mjs [--minify] [--check]
// web/legacy/entry.js (polyfills + ../app.js) -> web/legacy/app.legacy.js, one IIFE, syntax lowered to chrome53,
// with ./cat.js (three.js / WebGL2) replaced by web/legacy/videocat.js (loop videos from cats/video/).
// esbuild is a devDependency (package.json): run `npm install` once in the repo root.
// ESBUILD_DIR=<dir that contains esbuild/> uses an esbuild from another node_modules instead.
// --check: build to memory and fail if the committed app.legacy.js is stale (for the coordinator before a deploy).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const CANDIDATES = [process.env.ESBUILD_DIR, join(ROOT, 'node_modules')].filter(Boolean);
const dir = CANDIDATES.find((d) => existsSync(join(d, 'esbuild', 'package.json')));
if (!dir) { console.error('esbuild not found: run npm install (or set ESBUILD_DIR; tried ' + CANDIDATES.join(', ') + ')'); process.exit(3); }
const esbuild = createRequire(join(dir, 'noop.js'))('esbuild');

const swapCat = {
  name: 'swap-cat',
  setup(b) {
    b.onResolve({ filter: /^\.\/cat\.js$/ }, (a) => (a.importer.replace(/\\/g, '/').endsWith('/web/app.js') ? { path: join(ROOT, 'web', 'legacy', 'videocat.js') } : undefined));
    b.onResolve({ filter: /^three$/ }, () => ({ errors: [{ text: 'three.js must not end up in the legacy bundle' }] }));
  },
};

const OUT = join(ROOT, 'web', 'legacy', 'app.legacy.js');
const r = await esbuild.build({
  entryPoints: [join(ROOT, 'web', 'legacy', 'entry.js')], bundle: true, format: 'iife', target: ['chrome53'],
  minify: args.includes('--minify'), legalComments: 'none', charset: 'utf8', write: false, plugins: [swapCat], logLevel: 'warning',
  banner: { js: '/* GENERATED by dev/build_legacy.mjs from web/*.js + web/legacy/*.js (esbuild ' + esbuild.version + ', target chrome53). Do not edit. */' },
});
const code = r.outputFiles[0].text;
// guard: nothing Chrome 53 cannot parse may survive (esbuild lowers these; this catches a target change)
const bad = [/\?\.[a-zA-Z_$[(]/, /\?\?/, /\basync\s+function\b/, /\bawait\b/, /\bimport\s*\(/, /\bimport\.meta\b/].filter((re) => re.test(code.replace(/"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*'|`(?:[^`\\]|\\.)*`/g, '""')));
if (bad.length) { console.error('legacy bundle still contains', bad.map(String).join(' ')); process.exit(4); }
if (args.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== code) { console.error('web/legacy/app.legacy.js is STALE: run node dev/build_legacy.mjs'); process.exit(5); }
  console.log('web/legacy/app.legacy.js is up to date'); process.exit(0);
}
writeFileSync(OUT, code);
console.log(`wrote ${OUT} (${(code.length / 1024).toFixed(1)} KB, esbuild ${esbuild.version} from ${dir})`);
